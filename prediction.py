import pandas as pd
import numpy as np
import joblib


# ============================================================
# MODEL LOADING
# ============================================================

def load_xgboost_model(model_path):
    """
    Load the trained XGBoost model.

    Parameters
    ----------
    model_path : str
        Path to the saved XGBoost model.

    Returns
    -------
    model
        Loaded XGBoost model.
    """

    model = joblib.load(model_path)

    return model


# ============================================================
# FEATURE ALIGNMENT
# ============================================================

def align_features(X, model_features):
    """
    Align uploaded/preprocessed data with the feature structure
    expected by the trained XGBoost model.

    Missing features are filled with 0.
    Extra features are removed.

    Parameters
    ----------
    X : pandas.DataFrame
        Preprocessed uploaded dataset.

    model_features : list
        Feature names used when training the model.

    Returns
    -------
    X_aligned : pandas.DataFrame
    """

    X = X.copy()

    # Add missing training features
    for feature in model_features:
        if feature not in X.columns:
            X[feature] = 0

    # Keep only features used during training
    X_aligned = X[model_features]

    return X_aligned


# ============================================================
# RESPONSE PROBABILITY
# ============================================================

def predict_response_probability(
    model,
    X,
    model_features=None
):
    """
    Generate probability that each customer will subscribe
    to the term deposit.

    Parameters
    ----------
    model : trained XGBoost model

    X : pandas.DataFrame
        Preprocessed feature dataset.

    model_features : list, optional
        Features expected by the trained model.

    Returns
    -------
    probabilities : numpy.ndarray
        Probability of positive response for each customer.
    """

    X = X.copy()

    # Align uploaded data with training features
    if model_features is not None:
        X = align_features(
            X,
            model_features
        )

    # Probability of class 1 = "yes"
    probabilities = model.predict_proba(X)[:, 1]

    return probabilities


# ============================================================
# RESPONSE PREDICTION
# ============================================================

def predict_response(
    model,
    X,
    model_features=None,
    threshold=0.50
):
    """
    Generate response probability and predicted response.

    Parameters
    ----------
    model : trained XGBoost model

    X : pandas.DataFrame
        Preprocessed features.

    model_features : list, optional
        Features expected by the trained model.

    threshold : float
        Probability threshold for classifying a customer
        as likely to respond.

    Returns
    -------
    predictions : pandas.DataFrame
        Contains response probability and prediction.
    """

    probabilities = predict_response_probability(
        model=model,
        X=X,
        model_features=model_features
    )

    predictions = pd.DataFrame(
        index=X.index
    )

    predictions["response_probability"] = probabilities

    predictions["predicted_response"] = (
        probabilities >= threshold
    ).astype(int)

    return predictions


# ============================================================
# ADD PREDICTIONS TO CUSTOMER DATA
# ============================================================

def add_predictions_to_customer_data(
    df,
    predictions
):
    """
    Add model predictions to the original customer dataset.

    This creates the prediction layer of the
    Customer Intelligence dataset.

    Parameters
    ----------
    df : pandas.DataFrame
        Original/cleaned customer dataset.

    predictions : pandas.DataFrame
        Predictions generated by the model.

    Returns
    -------
    customer_data : pandas.DataFrame
    """

    customer_data = df.copy()

    customer_data["response_probability"] = (
        predictions["response_probability"]
    )

    customer_data["predicted_response"] = (
        predictions["predicted_response"]
    )

    return customer_data


# ============================================================
# COMPLETE PREDICTION PIPELINE
# ============================================================

def run_prediction_pipeline(
    df,
    X_transformed,
    model,
    model_features=None,
    threshold=0.50
):
    """
    Complete prediction pipeline.

    Takes the uploaded customer dataset and returns the
    original customer data enriched with model predictions.
    """

    predictions = predict_response(
        model=model,
        X=X_transformed,
        model_features=model_features,
        threshold=threshold
    )

    customer_data = add_predictions_to_customer_data(
        df=df,
        predictions=predictions
    )

    return customer_data